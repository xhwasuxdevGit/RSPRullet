// 1라운드 튜토리얼 안내 단계 (튜토리얼(1라운드) 세부 기획서 3장 가르칠 순서와 표시 시점).
// 말풍선 하나가 한 단계이고, 단계마다 띄우는 화면이 하나로 정해져 있다.
// 라운드 승리·패배를 빼면 첫 카드 셔플 안에서 순서대로 나오고, 두 번째 카드 셔플 시작에서 튜토리얼 종료 안내로 끝난다.
// TutorialSettings 에셋에는 순번(숫자)으로 저장되므로, 값을 중간에 넣거나 빼면 에셋 항목도 다시 맞춰야 한다.
// 새 단계는 맨 뒤에 추가한다
public enum TutorialStep
{
    CardPool,          // 안내-01: 카드풀 공개
    DecideFirst,       // 안내-02: 첫 선 정하기 결과 (비겨도 띄우고, 비기면 다시 섞는다는 설명을 함께 한다)
    PlayerDistribute,  // 안내-03: 플레이어 차례 판의 카드 뽑기 ([카드 뽑기] 버튼이 켜질 때)
    DealerDistribute,  // 안내-04: 딜러 차례 판의 뽑기·분배
    MatchResult,       // 안내-05: 판 결과 표시
    Settlement,        // 안내-06·07: 정산 표시 (말풍선 하나)
    RoundWin,          // 안내-08: 1라운드 승리
    TutorialEnd,       // 튜토리얼 종료: 두 번째 카드 셔플의 카드풀 공개
    RoundLose          // 안내-09: 1라운드 패배, 응급약 섭취 안내 (응급약을 처음 먹을 때만)
}
